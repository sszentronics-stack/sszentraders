export function getProductBySlug(slug) {
  return products.find((p) => p.slug === slug)
}

export function formatPKR(amount) {
  return `Rs.${amount.toLocaleString('en-US')}`
}

export function salePercent(product) {
  if (!product.compareAt || product.compareAt <= product.price) return 0
  return Math.round(((product.compareAt - product.price) / product.compareAt) * 100)
}

export function buildWhatsAppOrder(items, customer = {}) {
  const lines = items.map(
    (item) =>
      `• ${item.qty}x ${item.name} — ${formatPKR(item.price * item.qty)}`,
  )
  const total = items.reduce((sum, item) => sum + item.price * item.qty, 0)
  const header = [
    'Hello Aura Beauty Care, I would like to place an order:',
    '',
    ...lines,
    '',
    `Total: ${formatPKR(total)}`,
  ]
  if (customer.name || customer.city || customer.address) {
    header.push('', 'Delivery details:')
    if (customer.name) header.push(`Name: ${customer.name}`)
    if (customer.phone) header.push(`Phone: ${customer.phone}`)
    if (customer.city) header.push(`City: ${customer.city}`)
    if (customer.address) header.push(`Address: ${customer.address}`)
  }
  header.push('', 'Please confirm availability. Thank you!')
  return `${WHATSAPP_LINK}?text=${encodeURIComponent(header.join('\n'))}`
}

export function buildWhatsAppProduct(product, qty = 1) {
  return buildWhatsAppOrder([{ name: product.name, price: product.price, qty }])
}
